"""Authority-weighting experiment: count-QaL vs standing-weighted vs PageRank-QaL.

Two tests (see analysis/gaming_robustness for the count/standing baselines, Exhibit E):
  TEST 1 — honest-ranking agreement: how much does PageRank reshuffle the LEGITIMATE order vs raw count?
           (Spearman rho + top-decile Jaccard). High agreement => authority-weighting is a ~free hardening.
  TEST 2 — gaming resistance: run the Exhibit E 20-paper ring attack against each metric and report the
           percentile a p50/p75/p90 paper REACHES. PageRank should resist even in sparse fields, because a
           fabricated ring's nodes have ~zero eigenvector mass (nothing real cites them).

Data: a synthetic directed citation graph generated by a Price/preferential-attachment model with a
recency taper, calibrated so the in-degree (citation-count) distribution reproduces a DENSE field
(~Biochemistry, 46% uncited) and a SPARSE field (~Arts & Humanities, ~80% uncited). This demonstrates the
MECHANISM on realistic densities; a real-citation-graph confirmation needs the incoming-edge ingestion
(the same dependency as wiring pipeline/defended_score.py) and is specified in the README.

  python pagerank_experiment.py <out-dir>
"""
import sys, os, json
import numpy as np
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt

GAMMA = 2.0          # standing-weight convexity (matches Exhibit E)
RING = 20            # fabricated-ring size
SEED = 7


def price_graph(N, m, a, recency, rng):
    """Directed citation graph: paper t (in time order) cites min(m,t) earlier papers, chosen with
    probability proportional to (in_degree + a) * recency**(age). Returns src, dst arrays and in-degree."""
    src, dst = [], []
    indeg = np.zeros(N)
    idx = np.arange(N)
    for t in range(1, N):
        k = min(m, t)
        w = (indeg[:t] + a) * recency ** (t - idx[:t])   # prefer well-cited AND recent
        p = w / w.sum()
        tg = rng.choice(t, size=k, replace=False, p=p)
        for g in tg:
            src.append(t); dst.append(int(g)); indeg[g] += 1
    return np.array(src), np.array(dst), indeg


def pagerank(src, dst, N, d=0.85, iters=300, tol=1e-13, v=None):
    """Personalized PageRank. `v` is the teleport distribution (sums to 1); default uniform = vanilla
    PageRank. Concentrating `v` on trusted seed nodes (0 elsewhere) gives TrustRank: nodes with no
    teleport mass and no real inlinks — e.g. a fabricated ring — decay to ~0 authority."""
    outdeg = np.bincount(src, minlength=N).astype(float)
    dangling = outdeg == 0
    if v is None:
        v = np.full(N, 1.0 / N)
    inv = np.where(dangling, 0.0, 1.0 / np.where(outdeg == 0, 1, outdeg))
    pr = v.copy()
    for _ in range(iters):
        contrib = np.zeros(N)
        np.add.at(contrib, dst, pr[src] * inv[src])
        pr_new = (1 - d) * v + d * (contrib + pr[dangling].sum() * v)
        if np.abs(pr_new - pr).sum() < tol:
            pr = pr_new; break
        pr = pr_new
    return pr


def midrank_pct(values, x):
    """Mid-rank percentile of scalar x within array `values` (QaL convention)."""
    v = np.asarray(values)
    below = np.sum(v < x); eq = np.sum(v == x)
    return 100.0 * (below + 0.5 * eq) / len(v)


def standing_weight(src, dst, indeg, N, gamma):
    """Each paper's authority-by-standing score: sum over its citers of (citer's count-percentile/100)**g."""
    order = np.argsort(indeg)
    ranks = np.empty(N); ranks[order] = np.arange(N)
    standing = (ranks + 0.5) / N                 # citer standing in [0,1]
    sw = np.zeros(N)
    np.add.at(sw, dst, standing[src] ** gamma)
    return sw


def target_at(score, p):
    """Pick a node whose percentile under `score` is ~p."""
    order = np.argsort(score)
    return int(order[min(int(p / 100.0 * len(score)), len(score) - 1)])


def run_regime(name, N, m, a, recency, rng):
    src, dst, indeg = price_graph(N, m, a, recency, rng)
    pr = pagerank(src, dst, N)
    sw = standing_weight(src, dst, indeg, N, GAMMA)
    uncited = float(np.mean(indeg == 0))
    # TrustRank teleport vector: mass only on "established" seeds (top decile by citation count)
    seeds = np.argsort(indeg)[-max(1, N // 10):]
    vtrust = np.zeros(N); vtrust[seeds] = 1.0 / len(seeds)
    tr = pagerank(src, dst, N, v=vtrust)

    # TEST 1 — agreement of the honest ranking (count vs PageRank)
    def spearman(x, y):
        rx = np.argsort(np.argsort(x)); ry = np.argsort(np.argsort(y))
        return float(np.corrcoef(rx, ry)[0, 1])
    top = max(1, N // 10)
    jacc = len(set(np.argsort(indeg)[-top:]) & set(np.argsort(pr)[-top:])) / \
        len(set(np.argsort(indeg)[-top:]) | set(np.argsort(pr)[-top:]))

    # TEST 2 — 20-ring attack, fairly: select AND measure the target under each metric separately.
    # A fabricated ring member is a new, uncited paper; under standing-weight its standing sits at the
    # field's uncited-atom mid-rank (= uncited/2), exactly as in Exhibit E — NOT zero.
    floor_standing = uncited / 2.0
    ring_sw = RING * (floor_standing ** GAMMA)
    vtrust_ext = np.concatenate([vtrust, np.zeros(RING)])   # ring nodes are NOT trusted seeds

    def linkfarm(base_src, base_dst, t):
        ns, nd = list(base_src), list(base_dst); ids = list(range(N, N + RING))
        for i, r in enumerate(ids):
            ns.append(r); nd.append(t)                       # ring -> target
            ns.append(r); nd.append(ids[(i + 1) % RING])     # ring cycle (self-boost / link farm)
        return np.array(ns), np.array(nd)

    reach = {"count": {}, "standing": {}, "pagerank": {}, "trustrank": {}}
    for p in (50, 75, 90):
        t = target_at(indeg, p); reach["count"][p] = midrank_pct(indeg, indeg[t] + RING)
        t = target_at(sw, p);    reach["standing"][p] = midrank_pct(sw, sw[t] + ring_sw)
        t = target_at(pr, p)
        ns, nd = linkfarm(src, dst, t)
        reach["pagerank"][p] = midrank_pct(pagerank(ns, nd, N + RING)[:N],
                                           pagerank(ns, nd, N + RING)[t])
        t = target_at(tr, p)
        ns, nd = linkfarm(src, dst, t)
        pr_tr = pagerank(ns, nd, N + RING, v=vtrust_ext)
        reach["trustrank"][p] = midrank_pct(pr_tr[:N], pr_tr[t])
    return {"name": name, "N": N, "uncited_pct": round(100 * uncited, 1),
            "test1_spearman_count_vs_pr": round(spearman(indeg, pr), 3),
            "test1_top_decile_jaccard": round(jacc, 3),
            "test1_spearman_count_vs_trustrank": round(spearman(indeg, tr), 3),
            "test2_reach": {k: {p: round(v, 1) for p, v in d.items()} for k, d in reach.items()}}


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "."
    os.makedirs(out, exist_ok=True)
    rng = np.random.default_rng(SEED)
    regimes = [
        run_regime("Dense (~Biochemistry)", 8000, m=3, a=0.6, recency=0.9992, rng=rng),
        run_regime("Sparse (~Arts & Humanities)", 8000, m=1, a=0.15, recency=0.998, rng=rng),
    ]
    json.dump(regimes, open(os.path.join(out, "pagerank_results.json"), "w"), indent=1)

    # figure: reached percentile under each metric (both ring models for PageRank)
    fig, axes = plt.subplots(1, 2, figsize=(10.4, 4.6), sharey=True)
    fig.subplots_adjust(bottom=0.14, left=0.08, right=0.98, top=0.84, wspace=0.08)
    metrics = [("count", "#c0392b", "count-only"), ("standing", "#e8862e", "standing-weight (γ=2)"),
               ("pagerank", "#8e44ad", "vanilla PageRank"), ("trustrank", "#1b6fb0", "TrustRank (seeded)")]
    for ax, reg in zip(axes, regimes):
        xs = [50, 75, 90]
        ax.plot(xs, xs, color="#999", ls="--", lw=1, label="no attack")
        for key, col, lab in metrics:
            ax.plot(xs, [reg["test2_reach"][key][p] for p in xs], color=col, lw=2.2, marker="o", ms=5, label=lab)
        ax.axhspan(90, 100, color="#f2c94c", alpha=0.13)
        ax.set_title(f"{reg['name']} — {reg['uncited_pct']:.0f}% uncited", fontsize=10.5)
        ax.set_xlabel("Starting percentile", fontsize=10); ax.set_xlim(48, 92); ax.set_ylim(28, 101)
        ax.grid(True, color="#eee", lw=0.6)
        for s in ("top", "right"): ax.spines[s].set_visible(False)
    axes[0].set_ylabel("Percentile reached after a 20-ring", fontsize=10)
    axes[1].legend(frameon=False, fontsize=8.5, loc="center right")
    fig.suptitle("Vanilla PageRank is link-farm-gameable too — only trust-seeded authority (TrustRank) resists\n"
                 "lines above the dashed diagonal = the ring lifted the paper; only TrustRank stays at/below it",
                 fontsize=11, x=0.02, ha="left")
    fig.savefig(os.path.join(out, "fig_pagerank_gaming.png"), dpi=150, facecolor="white")
    print("wrote", os.path.join(out, "fig_pagerank_gaming.png"))
    for r in regimes:
        t2 = r["test2_reach"]
        print(f"  {r['name']:28} uncited={r['uncited_pct']}%  Test1: rho={r['test1_spearman_count_vs_pr']} "
              f"top10-Jaccard={r['test1_top_decile_jaccard']}")
        print(f"      Test2 p75 reached: count p{t2['count'][75]}  standing p{t2['standing'][75]}  "
              f"PageRank p{t2['pagerank'][75]}")


if __name__ == "__main__":
    main()
